const { sha256 } = require("./core.js");

function syntheticFixture() {
  const sources = [
    { id: "demo-a", title: "Long Tail Learning", pages: ["Long-tail recognition improves rare class accuracy with class-balanced training.", "A teacher model transfers knowledge to a student using distillation."] },
    { id: "demo-b", title: "Privacy in Federated Learning", pages: ["Federated learning keeps raw data on the client device.", "Differential privacy adds calibrated noise to model updates."] },
    { id: "demo-c", title: "Unrelated Image Compression", pages: ["Image compression reduces bandwidth by quantizing pixel data."] }
  ];
  const papers = sources.map((source) => {
    let text = "";
    const pageTextOffsets = source.pages.map((page, index) => {
      if (index) text += "\n\n";
      const start = text.length;
      text += page;
      return { pageNumber: index + 1, start, end: text.length };
    });
    return { id: source.id, title: source.title, source: "Generated by scripts/evaluation/synthetic.js", text, pageCount: source.pages.length, pageTextOffsets, keywords: [] };
  });
  const questions = [
    { id: "q1", query: "rare class accuracy", type: "English exact", split: "development", answerable: true, reviewedBy: "test fixture", notes: "Exact evidence", evidence: [{ id: "e1", paperId: "demo-a", pageNumber: 1, quote: "rare class accuracy", relevance: 2 }] },
    { id: "q2", query: "What does the teacher transfer to the student?", type: "English paraphrase", split: "test", answerable: true, reviewedBy: "test fixture", notes: "Paraphrase exercise", evidence: [{ id: "e2", paperId: "demo-a", pageNumber: 2, quote: "transfers knowledge to a student", relevance: 2 }] },
    { id: "q3", query: "federated learning, differential privacy", type: "two concepts", split: "development", answerable: true, reviewedBy: "test fixture", notes: "Two separate evidence units", evidence: [
      { id: "e3", paperId: "demo-b", pageNumber: 1, quote: "keeps raw data on the client device", relevance: 2 },
      { id: "e4", paperId: "demo-b", pageNumber: 2, quote: "adds calibrated noise to model updates", relevance: 2 }
    ] },
    { id: "q4", query: "quantum entanglement circuits", type: "unanswerable", split: "test", answerable: false, reviewedBy: "test fixture", notes: "No source mentions this", evidence: [] }
  ];
  const corpus = { schemaVersion: 1, id: "synthetic-mini", version: "1", kind: "synthetic", source: "Generated fixture; no source papers", papers };
  const annotations = { schemaVersion: 1, id: "synthetic-mini-questions", version: "1", kind: "synthetic", source: "Generated fixture", questions };
  const { prepare, embeddingInputs } = require("./core.js");
  const prepared = prepare(corpus, annotations, { split: "all" });
  // A deterministic topic lookup for exercising code paths. These are not model embeddings.
  const classify = (text) => {
    const value = text.toLowerCase();
    if (/quantum|entanglement/.test(value)) return [0, 0, 0, 1];
    if (/teacher|student|distillation/.test(value)) return [0, 1, 0, 0];
    if (/privacy|federated|client|noise/.test(value)) return [0, 0, 1, 0];
    return [1, 0, 0, 0];
  };
  const vectors = {
    schemaVersion: 1, kind: "synthetic",
    model: { provider: "synthetic lookup", name: "topic-fixture", revision: "1", preprocessing: "lowercase keyword matching", dimensions: 4 },
    entries: embeddingInputs(prepared).entries.map((entry) => ({ textHash: sha256(entry.text), vector: classify(entry.text) }))
  };
  return { corpus, questions: annotations, vectors };
}

module.exports = { syntheticFixture };
